// Records only the synthetic browser viewport, never the desktop or browser chrome.
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
const module=process.argv[2]||'playwright';
const {chromium}=await import(module.startsWith('/')?pathToFileURL(module).href:module);
fs.mkdirSync('media',{recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROMIUM||'/usr/bin/chromium',headless:true,args:['--disable-gpu']});
const page=await browser.newPage({viewport:{width:1440,height:1280},deviceScaleFactor:1});
const ffmpeg=spawn('ffmpeg',['-n','-hide_banner','-loglevel','error','-f','image2pipe','-framerate','10','-vcodec','mjpeg','-i','pipe:0','-c:v','libx264','-pix_fmt','yuv420p','-crf','22','-movflags','+faststart','-an','media/pixcam-aurora-72s.mp4'],{stdio:['pipe','ignore','inherit']});
const finished=once(ffmpeg,'close');
const caption=async text=>page.evaluate(text=>{const el=document.getElementById('tour-caption');el.hidden=false;el.textContent=text;},text);
const steps=new Map([
 [0,async()=>caption('pixCAM / Aurora — original synthetic data, Rust-powered inspection')],
 [70,async()=>{await page.click('#top');await caption('Seven holes, one slot, one pocket. All dimensions are synthetic.');}],
 [140,async()=>{await page.selectOption('#face','Z_MAX');await page.selectOption('#diameter','6');await caption('Filter by orientation and diameter: three top-face Ø6 holes.');}],
 [200,async()=>{await page.click('#reset');await page.click('[data-id="S01"]');await caption('Inspect coordinates, inward axis, feature type and data source.');}],
 [260,async()=>{await page.click('[data-id="P01"]');await caption('Slot and pocket contours are explicit annotations, not CAD recognition.');}],
 [320,async()=>{await page.click('#groups-tab');await caption('Five orientation / tool groups. Tool choices remain illustrative.');}],
 [390,async()=>{await page.click('#nc-tab');await page.click('#play');await caption('ISO-NC 3D: amber rapids, teal linear feeds, purple arcs.');}],
 [480,async()=>caption('Playback follows distance, not machining time. No collision or material-removal simulation.')],
 [570,async()=>{await page.click('#map-tab');await caption('Export JSON, CSV, SVG or DXF — all generated by Rust, available offline.');}],
 [640,async()=>{await page.locator('#limits').evaluate(el=>el.open=true);await page.locator('#limits').scrollIntoViewIfNeeded();await caption('A focused inspection companion. Unsupported NC is rejected; no production approval.');}],
 [690,async()=>caption('pixCAM / Public showcase v0.1 — ready for community review')],
]);
try{
 await page.goto(pathToFileURL(path.resolve('dist/index.html')).href);
 const start=performance.now();
 for(let frame=0;frame<720;frame++){
  if(steps.has(frame))await steps.get(frame)();
  const bytes=await page.screenshot({type:'jpeg',quality:83});
  if(!ffmpeg.stdin.write(bytes))await once(ffmpeg.stdin,'drain');
  const delay=(frame+1)*100-(performance.now()-start);if(delay>0)await new Promise(resolve=>setTimeout(resolve,delay));
 }
 ffmpeg.stdin.end();const [code]=await finished;if(code!==0)throw new Error(`ffmpeg exit ${code}`);
 console.log('Recorded 720 browser frames / 72 seconds, 1440×1280, no desktop capture.');
}finally{await browser.close();if(ffmpeg.exitCode===null)ffmpeg.kill();}
